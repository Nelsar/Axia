#!/usr/bin/env python3
"""Writes bulk-users.ldif: a few hundred accounts across department units, each with a unique
mail to sign in with, plus a group per department.

Seeded, so the same file comes out every time and is safe to regenerate:

    python3 deploy/dev/generate-bulk-users.py            # 300 accounts
    python3 deploy/dev/generate-bulk-users.py --count 500

The file is loaded on the first start of an empty directory (see docker-compose.ldap.yml). To add
it to one that is already running:

    ldapadd -x -H ldap://127.0.0.1 -D cn=admin,dc=example,dc=org -w adminpassword -c -f deploy/dev/bulk-users.ldif

Every password is Axia-Demo-1. Values are ASCII, so the LDIF needs no base64.
"""

import argparse
import random
from pathlib import Path

BASE = "dc=example,dc=org"
STAFF = f"ou=staff,ou=people,{BASE}"
GROUPS = f"ou=groups,{BASE}"
PASSWORD = "Axia-Demo-1"

# it and sales already exist (test-data.ldif); the rest are created here.
DEPARTMENTS = {
    "it": ("IT department", ["Developer", "System administrator", "QA engineer", "DevOps engineer", "Support engineer"]),
    "sales": ("Sales department", ["Sales manager", "Account manager", "Sales assistant", "Key account manager"]),
    "finance": ("Finance department", ["Accountant", "Financial analyst", "Chief accountant", "Payroll specialist"]),
    "hr": ("Human resources", ["HR manager", "Recruiter", "HR specialist"]),
    "marketing": ("Marketing department", ["Marketing manager", "Content manager", "Designer", "SMM specialist"]),
    "support": ("Customer support", ["Support agent", "Support team lead", "Quality specialist"]),
    "logistics": ("Logistics department", ["Logistics coordinator", "Warehouse manager", "Driver", "Dispatcher"]),
    "legal": ("Legal department", ["Lawyer", "Legal counsel", "Compliance officer"]),
}
NEW_UNITS = [d for d in DEPARTMENTS if d not in ("it", "sales")]

GIVEN = [
    "Aidar", "Aigul", "Aizhan", "Akbota", "Alibek", "Almas", "Amina", "Arman", "Arsen", "Asem",
    "Askar", "Ayana", "Azamat", "Bakhyt", "Baurzhan", "Dana", "Darkhan", "Dauren", "Dilnaz", "Erlan",
    "Gaukhar", "Kairat", "Kamila", "Madina", "Marat", "Meruert", "Nurlan", "Nursultan", "Raushan", "Sanzhar",
    "Saltanat", "Serik", "Togzhan", "Yerbol", "Zarina", "Zhanna", "Zhandos",
    "Alexei", "Anna", "Dmitry", "Ekaterina", "Igor", "Irina", "Maxim", "Natalia", "Oleg", "Pavel",
    "Sergey", "Svetlana", "Tatiana", "Viktor", "Yulia",
    "Daniel", "Emily", "James", "Laura", "Michael", "Sarah", "Thomas", "Sofia", "Lucas", "Mia",
]
SURNAMES = [
    "Abenov", "Akhmetov", "Alimov", "Baimukhanov", "Bekov", "Dzhaksybekov", "Ermekov", "Iskakov", "Kaliyev",
    "Kassymov", "Kenzhebayev", "Mukanov", "Nazarbekov", "Omarov", "Rakhimov", "Sadykov", "Seitkali", "Suleimenov",
    "Tokayev", "Utepov", "Zhakupov", "Zhumabayev",
    "Ivanov", "Kuznetsov", "Morozov", "Novikov", "Orlov", "Pavlov", "Popov", "Smirnov", "Sokolov", "Volkov",
    "Brown", "Davis", "Garcia", "Johnson", "Miller", "Schmidt", "Taylor", "Wilson",
]


def entry(dn, attributes):
    lines = [f"dn: {dn}"]
    for name, value in attributes:
        lines.append(f"{name}: {value}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--count", type=int, default=300)
    parser.add_argument("--seed", type=int, default=20261010)
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("bulk-users.ldif"))
    args = parser.parse_args()

    rng = random.Random(args.seed)
    blocks = [
        f"# Generated by generate-bulk-users.py --count {args.count} --seed {args.seed}. Do not edit by hand.\n"
        f"# {args.count} accounts across {len(DEPARTMENTS)} units; every password is {PASSWORD}."
    ]

    for unit in NEW_UNITS:
        blocks.append(entry(f"ou={unit},{STAFF}", [
            ("objectClass", "organizationalUnit"), ("ou", unit), ("description", DEPARTMENTS[unit][0]),
        ]))

    # Names the hand-written LDIFs already use, so a generated login never collides with them.
    taken = {"timur.akhmetov", "saule.bekova", "daniyar.omarov", "olga.sidorova", "asel.karimova",
             "ivan.petrov", "aliya.nurlanova", "maria.garcia", "john.smith"}
    members = {unit: [] for unit in DEPARTMENTS}
    units = list(DEPARTMENTS)

    for number in range(1, args.count + 1):
        given, surname = rng.choice(GIVEN), rng.choice(SURNAMES)
        base_uid = f"{given}.{surname}".lower()
        uid, suffix = base_uid, 2
        while uid in taken:
            uid, suffix = f"{base_uid}{suffix}", suffix + 1
        taken.add(uid)

        unit = rng.choice(units)
        dn = f"uid={uid},ou={unit},{STAFF}"
        members[unit].append(dn)
        blocks.append(entry(dn, [
            ("objectClass", "inetOrgPerson"),
            ("uid", uid),
            ("cn", f"{given} {surname}"),
            ("sn", surname),
            ("givenName", given),
            ("displayName", f"{given} {surname}"),
            ("mail", f"{uid}@example.org"),
            ("title", rng.choice(DEPARTMENTS[unit][1])),
            ("departmentNumber", unit),
            ("employeeNumber", f"E{number:05d}"),
            ("telephoneNumber", f"+7 7{rng.randint(0, 9)}{rng.randint(0, 9)} {rng.randint(100, 999)} {rng.randint(1000, 9999)}"),
            ("userPassword", PASSWORD),
        ]))

    # A group per department. test-data.ldif already has "sales" and "it-staff", so these are
    # named dept-* to stay clear of them.
    for unit, dns in members.items():
        if not dns:
            continue
        blocks.append(entry(f"cn=dept-{unit},{GROUPS}", [
            ("objectClass", "groupOfNames"), ("cn", f"dept-{unit}"),
            ("description", f"{DEPARTMENTS[unit][0]} (generated)"),
            *[("member", dn) for dn in dns],
        ]))

    args.out.write_text("\n\n".join(blocks) + "\n", encoding="ascii")
    print(f"Wrote {args.out}: {args.count} accounts, "
          + ", ".join(f"{unit} {len(dns)}" for unit, dns in members.items()))


if __name__ == "__main__":
    main()
